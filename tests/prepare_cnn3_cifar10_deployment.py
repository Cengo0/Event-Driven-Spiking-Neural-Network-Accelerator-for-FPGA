#!/usr/bin/env python3
"""
prepare_cnn3_cifar10_deployment.py
==================================
Prepares deployment payload for 3-layer CIFAR-10 Convolutional SNN (CNN3) on PYNQ-Z2 FPGA.
Calibrates full 8-bit [-127, +127] Layer 3 weights (q_fc_w) and 16-bit Layer 3
threshold (hw_threshold_l3) using the exact un-coalesced Phase 3 stream from
snn_top_hls.cpp (including Phase 2a CONV2_BIAS addition) and event-driven bias folding.
"""

import os
import sys
import json
import argparse
import numpy as np
import torch
import torch.nn as nn


CIFAR10_CLASSES = [
    "airplane", "automobile", "bird", "cat", "deer",
    "dog", "frog", "horse", "ship", "truck"
]


def fuse_batchnorm_conv(w, b, bn_gamma, bn_beta, bn_mean, bn_var, eps=1e-5):
    """Fold 2D BatchNorm parameters into Conv2d weights and biases."""
    std = torch.sqrt(bn_var + eps)
    w_fused = w * (bn_gamma / std).view(-1, 1, 1, 1)
    if b is None:
        b = torch.zeros(w.size(0))
    if bn_beta is not None:
        b_fused = (b - bn_mean) * (bn_gamma / std) + bn_beta
    else:
        b_fused = (b - bn_mean) * (bn_gamma / std)
    return w_fused.numpy(), b_fused.numpy()


def export_hls_weights_header(w1_f, b1_f, q_conv2_int, q_conv2_bias_int16, header_path):
    """
    Auto-generate C++ header containing Conv1 float weights/biases (3-channel RGB) and
    Conv2 int8 weights + int16 biases for HLS Streaming 2D Convolution Engine.
    """
    os.makedirs(os.path.dirname(os.path.abspath(header_path)), exist_ok=True)
    with open(header_path, 'w') as f:
        f.write("// Auto-generated CIFAR-10 CNN3 weights for HLS Streaming Engine\n")
        f.write("// Generated by tests/prepare_cnn3_cifar10_deployment.py\n")
        f.write("#ifndef CNN3_WEIGHTS_H\n")
        f.write("#define CNN3_WEIGHTS_H\n\n")

        # CONV1_WEIGHTS [8][3][3][3]
        f.write(f"static const float CONV1_WEIGHTS[{w1_f.shape[0]}][{w1_f.shape[1]}][{w1_f.shape[2]}][{w1_f.shape[3]}] = {{\n")
        for co in range(w1_f.shape[0]):
            f.write(f"    {{ // Out Channel {co}\n")
            for ci in range(w1_f.shape[1]):
                f.write(f"        {{ // In Channel {ci} (RGB)\n")
                for dy in range(w1_f.shape[2]):
                    row = ", ".join([f"{w1_f[co, ci, dy, dx]:.6f}f" for dx in range(w1_f.shape[3])])
                    f.write(f"            {{ {row} }},\n")
                f.write("        },\n")
            f.write("    },\n")
        f.write("};\n\n")

        # CONV1_BIAS [8]
        f.write(f"static const float CONV1_BIAS[{b1_f.shape[0]}] = {{\n    ")
        f.write(", ".join([f"{b:.6f}f" for b in b1_f]))
        f.write("\n};\n\n")

        # CONV2_WEIGHTS [16][8][3][3] - Full precision integer weights
        f.write(f"static const signed char CONV2_WEIGHTS[{q_conv2_int.shape[0]}][{q_conv2_int.shape[1]}][{q_conv2_int.shape[2]}][{q_conv2_int.shape[3]}] = {{\n")
        for co in range(q_conv2_int.shape[0]):
            f.write(f"    {{ // Out Channel {co}\n")
            for ci in range(q_conv2_int.shape[1]):
                f.write(f"        {{ // In Channel {ci}\n")
                for dy in range(q_conv2_int.shape[2]):
                    row = ", ".join([f"{int(q_conv2_int[co, ci, dy, dx]):4d}" for dx in range(q_conv2_int.shape[3])])
                    f.write(f"            {{ {row} }},\n")
                f.write("        },\n")
            f.write("    },\n")
        f.write("};\n\n")

        # CONV2_BIAS [16] - Scaled integer biases (4 * SCALE2 * b2_f) for HLS Phase 2a
        f.write(f"static const short CONV2_BIAS[{len(q_conv2_bias_int16)}] = {{\n    ")
        f.write(", ".join([f"{int(b)}" for b in q_conv2_bias_int16]))
        f.write("\n};\n\n")

        f.write("#endif // CNN3_WEIGHTS_H\n")
    print(f"Auto-generated HLS C++ weights header: {header_path}")


def parse_args():
    parser = argparse.ArgumentParser(description="Prepare CIFAR-10 CNN3 SNN Deployment Payload for FPGA")
    parser.add_argument('--model', default='models/cifar_cnn3_T_4_clean_l2[0.000500].pth',
                        help='Path to PyTorch .pth model checkpoint')
    parser.add_argument('--output', default='data/cache/cifar10_cnn3_deployment.npz',
                        help='Output deployment payload path')
    parser.add_argument('--bias-report', '--bias-json', dest='bias_report',
                        default='data/cache/cifar10_cnn3_bias_report.json',
                        help='Output path for the detailed JSON bias diagnostic report')
    parser.add_argument('--hls-header', default='hardware/hls/include/cnn3_weights.h',
                        help='Path to output auto-generated HLS weights C++ header')
    parser.add_argument('--timesteps', type=int, default=4,
                        help='Number of SNN timesteps (default: 4)')
    parser.add_argument('--normalization', choices=['auto', 'zscore', 'raw'], default='auto',
                        help='Input normalization strategy (default: auto)')
    parser.add_argument('--samples', type=int, default=1000,
                        help='Number of validation images for threshold calibration (default: 1000)')
    return parser.parse_args()


def main():
    args = parse_args()
    MODEL_PATH = args.model
    OUTPUT_PATH = args.output
    BIAS_REPORT_PATH = args.bias_report
    TIMESTEPS = args.timesteps

    # ─────────────────────────────────────────────────────────────────
    # 1. Load Model Checkpoint & Extract Parameters
    # ─────────────────────────────────────────────────────────────────
    print(f"Loading PyTorch CIFAR-10 CNN3 model: {MODEL_PATH}")
    if not os.path.exists(MODEL_PATH):
        print(f"ERROR: Model file not found: {MODEL_PATH}")
        sys.exit(1)

    state_dict = torch.load(MODEL_PATH, map_location='cpu')

    # Layer 1 (Conv1): features.0
    l1_has_raw_bias = 'features.0.bias' in state_dict
    l1_has_bn = ('features.1.running_var' in state_dict and 'features.1.weight' in state_dict)
    if l1_has_bn:
        print("  Layer 1: Fusing BatchNorm into Conv1...")
        w1_f, b1_f = fuse_batchnorm_conv(
            state_dict['features.0.weight'],
            state_dict.get('features.0.bias', None),
            state_dict['features.1.weight'],
            state_dict.get('features.1.bias', None),
            state_dict['features.1.running_mean'],
            state_dict['features.1.running_var']
        )
        l1_bias_nature = 'fused_batchnorm_and_conv2d_bias' if l1_has_raw_bias else 'fused_batchnorm'
        l1_source_keys = [k for k in ['features.0.weight', 'features.0.bias', 'features.1.weight', 'features.1.bias', 'features.1.running_mean', 'features.1.running_var'] if k in state_dict]
    else:
        w1_f = state_dict['features.0.weight'].numpy()
        b1_f = state_dict['features.0.bias'].numpy() if l1_has_raw_bias else np.zeros(w1_f.shape[0], dtype=np.float32)
        l1_bias_nature = 'explicit_conv2d_bias' if (l1_has_raw_bias and not np.all(b1_f == 0)) else 'none_zero'
        l1_source_keys = [k for k in ['features.0.weight', 'features.0.bias'] if k in state_dict]

    # Layer 2 (Conv2): features.3 (or features.2 if no pool)
    conv2_w_key = 'features.3.weight' if 'features.3.weight' in state_dict else 'features.2.weight'
    conv2_b_key = 'features.3.bias' if 'features.3.bias' in state_dict else 'features.2.bias'
    l2_has_raw_bias = conv2_b_key in state_dict
    w2_f = state_dict[conv2_w_key].numpy()
    b2_f = state_dict[conv2_b_key].numpy() if l2_has_raw_bias else np.zeros(w2_f.shape[0], dtype=np.float32)
    l2_bias_nature = 'explicit_conv2d_bias' if (l2_has_raw_bias and not np.all(b2_f == 0)) else 'none_zero'
    l2_source_keys = [k for k in [conv2_w_key, conv2_b_key] if k in state_dict]

    # Layer 3 (Classifier): classifier
    l3_has_raw_bias = 'classifier.bias' in state_dict
    w3_f = state_dict['classifier.weight'].numpy()
    b3_f = state_dict['classifier.bias'].numpy() if l3_has_raw_bias else np.zeros(w3_f.shape[0], dtype=np.float32)
    l3_bias_nature = 'explicit_linear_bias' if (l3_has_raw_bias and not np.all(b3_f == 0)) else 'none_zero'
    l3_source_keys = [k for k in ['classifier.weight', 'classifier.bias'] if k in state_dict]

    has_biases = not (np.all(b1_f == 0) and np.all(b2_f == 0) and np.all(b3_f == 0))
    print(f"Model Biases Detected: {'Yes (fused/explicit)' if has_biases else 'No (bias=False / zero bias)'}")
    print(f"  Layer 1 (Conv1) shape: {w1_f.shape} (Input {w1_f.shape[1]} -> {w1_f.shape[0]} Output Channels, 3x3) | Bias: {l1_bias_nature}")
    print(f"  Layer 2 (Conv2) shape: {w2_f.shape} (Channels {w2_f.shape[1]} -> {w2_f.shape[0]}, 3x3) | Bias: {l2_bias_nature}")
    print(f"  Layer 3 (Linear) shape: {w3_f.shape} (Flattened {w3_f.shape[1]} -> {w3_f.shape[0]} Classes) | Bias: {l3_bias_nature}")
    print(f"  Layer 2 Biases (b2_f): {[round(float(x), 4) for x in b2_f]}")
    print(f"  Layer 3 Biases (b3_f): {[round(float(x), 4) for x in b3_f]}")

    # ─────────────────────────────────────────────────────────────────
    # 2. Dataset Loading & Auto-Detection of Normalization
    # ─────────────────────────────────────────────────────────────────
    try:
        from torchvision import datasets, transforms
    except ImportError:
        print("ERROR: torchvision is required to load CIFAR-10 dataset.")
        sys.exit(1)

    print("\nLoading CIFAR-10 Test Dataset...")
    CIFAR_MEAN = (0.4914, 0.4822, 0.4465)
    CIFAR_STD = (0.2023, 0.1994, 0.2010)
    raw_ds = datasets.CIFAR10('./data', train=False, download=True, transform=transforms.ToTensor())
    zscore_transform = transforms.Compose([
        transforms.ToTensor(),
        transforms.Normalize(CIFAR_MEAN, CIFAR_STD)
    ])
    zscore_ds = datasets.CIFAR10('./data', train=False, download=False, transform=zscore_transform)

    if args.normalization == 'auto':
        probe_loader_z = torch.utils.data.DataLoader(zscore_ds, batch_size=100, shuffle=False)
        probe_loader_r = torch.utils.data.DataLoader(raw_ds, batch_size=100, shuffle=False)
        imgs_z, lbls_z = next(iter(probe_loader_z))
        imgs_r, lbls_r = next(iter(probe_loader_r))

        conv1_t = nn.Conv2d(w1_f.shape[1], w1_f.shape[0], 3, padding=1)
        conv1_t.weight.data = torch.from_numpy(w1_f)
        conv1_t.bias.data = torch.from_numpy(b1_f)
        pool1_t = nn.AvgPool2d(2, 2)
        conv2_t = nn.Conv2d(w2_f.shape[1], w2_f.shape[0], 3, padding=1)
        conv2_t.weight.data = torch.from_numpy(w2_f)
        conv2_t.bias.data = torch.from_numpy(b2_f)
        pool2_t = nn.AvgPool2d(2, 2)
        fc_t = nn.Linear(w3_f.shape[1], w3_f.shape[0])
        fc_t.weight.data = torch.from_numpy(w3_f)
        fc_t.bias.data = torch.from_numpy(b3_f)

        def eval_probe(imgs, lbls):
            v1 = torch.zeros(100, w1_f.shape[0], 32, 32)
            v2 = torch.zeros(100, w2_f.shape[0], 16, 16)
            out_v = torch.zeros(100, 10)
            cur1 = conv1_t(imgs)
            for t in range(TIMESTEPS):
                v1 += cur1
                s1 = (v1 >= 1.0).float()
                v1 -= s1 * 1.0
                p1 = pool1_t(s1)
                cur2 = conv2_t(p1)
                v2 += cur2
                s2 = (v2 >= 1.0).float()
                v2 -= s2 * 1.0
                p2 = pool2_t(s2)
                out_v += fc_t(p2.view(100, -1))
            return (out_v.argmax(dim=1) == lbls).float().mean().item()

        with torch.no_grad():
            acc_z = eval_probe(imgs_z, lbls_z)
            acc_r = eval_probe(imgs_r, lbls_r)

        if acc_z >= acc_r:
            selected_norm = 'zscore'
            print(f"Auto-Detected Normalization: Z-Score Normalized (Probe Acc: Z={acc_z*100:.1f}% vs Raw={acc_r*100:.1f}%)")
        else:
            selected_norm = 'raw'
            print(f"Auto-Detected Normalization: Raw [0, 1] Intensities (Probe Acc: Raw={acc_r*100:.1f}% vs Z={acc_z*100:.1f}%)")
    else:
        selected_norm = args.normalization
        print(f"Using Specified Normalization: {selected_norm}")

    active_ds = zscore_ds if selected_norm == 'zscore' else raw_ds
    test_imgs = np.stack([img.numpy() for img, _ in active_ds])  # shape (10000, 3, 32, 32)
    test_lbls = np.array([lbl for _, lbl in active_ds], dtype=np.int64)
    print(f"  Loaded {len(test_imgs)} CIFAR-10 test images, shape: {test_imgs.shape}")

    # ─────────────────────────────────────────────────────────────────
    # 3. Dynamic Weight Scaling for Layer 2 (HLS Conv2 Engine)
    # ─────────────────────────────────────────────────────────────────
    max_abs_conv2 = np.max(np.abs(w2_f))
    SCALE2 = 127.0 / max_abs_conv2
    base_th = max(1, int(round(SCALE2)))
    q_conv2_int = np.clip(np.round(w2_f * SCALE2), -127, 127).astype(np.int8)
    # In snn_top_hls.cpp Phase 1, Conv1 spikes in a 2x2 block are summed (0..4),
    # and in Phase 3, threshold_l2 = base_th << 2 (4 * base_th).
    # Therefore, CONV2_BIAS added once per timestep in Phase 2a is scaled by 4 * SCALE2:
    q_b2_hls = np.round(4.0 * SCALE2 * b2_f).astype(np.int16)
    q_b2 = np.clip(np.round(b2_f * SCALE2), -127, 127).astype(np.int8)
    print(f"\nFPGA Layer 2 Dynamic Weight Scale: {SCALE2:.2f} (HLS Layer 2 Threshold = {base_th}, Eff. 4x Th = {base_th * 4})")
    print(f"  HLS Phase 2a CONV2_BIAS (4*SCALE2*b2_f): {q_b2_hls.tolist()}")

    # ─────────────────────────────────────────────────────────────────
    # 4. Exact HLS Phase 1/2/3 Emulation & Sequential L3 Calibration
    # ─────────────────────────────────────────────────────────────────
    print(f"\nRunning Exact HLS Phase 1-3 + RTL Group 4 Sequential Calibration Sweep...")
    n_calib = min(args.samples, len(test_imgs))
    calib_imgs = torch.from_numpy(test_imgs[:n_calib]).float()
    calib_lbls = test_lbls[:n_calib]

    conv1_calib = nn.Conv2d(w1_f.shape[1], w1_f.shape[0], 3, padding=1)
    conv1_calib.weight.data = torch.from_numpy(w1_f)
    conv1_calib.bias.data = torch.from_numpy(b1_f)
    # Sum-pooling in Phase 1 (4 * AvgPool2d) + Phase 2a CONV2_BIAS + Phase 3 threshold_l2 = 4 * base_th:
    pool1_sum = nn.AvgPool2d(2, 2, divisor_override=1)
    pool2_sum = nn.AvgPool2d(2, 2, divisor_override=1)
    q_conv2_t = torch.from_numpy(q_conv2_int.astype(np.float32))
    q_b2_hls_t = torch.from_numpy(q_b2_hls.astype(np.float32))
    th_l2_eff = float(base_th * 4)

    p2_calib = np.zeros((n_calib, TIMESTEPS, 1024), dtype=np.int32)
    with torch.no_grad():
        v1 = torch.zeros(n_calib, w1_f.shape[0], 32, 32)
        v2 = torch.zeros(n_calib, w2_f.shape[0], 16, 16)
        cur1 = conv1_calib(calib_imgs)
        for t in range(TIMESTEPS):
            v1 += cur1
            s1 = (v1 >= 1.0).float()
            v1 -= s1 * 1.0
            p1 = pool1_sum(s1)
            cur2 = nn.functional.conv2d(p1, q_conv2_t, bias=q_b2_hls_t, padding=1)
            v2 += cur2
            s2 = (v2 >= th_l2_eff).float()
            v2 -= s2 * th_l2_eff
            # Exact sum of 2x2 sub-pixels (0..4 spikes per pool bin across 16x8x8 = 1024 bins)
            p2 = pool2_sum(s2).view(n_calib, 1024).numpy()
            p2_calib[:, t, :] = np.round(p2).astype(np.int32)

    avg_l2_events = max(1.0, float(np.mean(np.sum(p2_calib, axis=(1, 2)))))
    print(f"  Empirical Layer 2 Routed Events / Image : {avg_l2_events:.1f} (across 1,024 L2 neurons in Groups 0..3)")

    # Pre-build padded 2D event index arrays per timestep: shape (n_calib, max_events_t)
    # Index 1024 maps to a zero-weight dummy synapse when an image has fewer events than max_events_t
    N_L2 = w3_f.shape[1]
    padded_events_calib = []
    for t in range(TIMESTEPS):
        ts_lists = []
        max_len = 0
        for i in range(n_calib):
            active_srcs = np.nonzero(p2_calib[i, t] > 0)[0]
            expanded = np.repeat(active_srcs, p2_calib[i, t, active_srcs])
            ts_lists.append(expanded)
            if len(expanded) > max_len:
                max_len = len(expanded)
        arr_t = np.full((n_calib, max_len), N_L2, dtype=np.int32)
        for i, seq in enumerate(ts_lists):
            if len(seq) > 0:
                arr_t[i, :len(seq)] = seq
        padded_events_calib.append(arr_t)

    def simulate_sequential_batch(q_fc_mat, padded_events_list, th_l3_val, batch_size):
        """Exact cycle-accurate sequential LIF simulation vectorized across batch_size images."""
        # Pad q_fc_mat (10, N_L2) with a zero column at index N_L2 -> shape (N_L2 + 1, 10)
        q_fc_pad = np.zeros((N_L2 + 1, 10), dtype=np.int32)
        q_fc_pad[:N_L2, :] = q_fc_mat.T
        v4 = np.zeros((batch_size, 10), dtype=np.int32)
        spk_out = np.zeros((batch_size, 10), dtype=np.int32)
        max_ts_spk = 0
        for t in range(TIMESTEPS):
            ev_t = padded_events_list[t]
            ts_spk = np.zeros(batch_size, dtype=np.int32)
            for e_idx in range(ev_t.shape[1]):
                v4 += q_fc_pad[ev_t[:, e_idx]]
                np.maximum(v4, 0, out=v4)
                fired = (v4 >= th_l3_val)
                if np.any(fired):
                    spk_out += fired
                    ts_spk += np.sum(fired, axis=1)
                    v4[fired] = 0
            if batch_size > 0:
                m_ts = int(np.max(ts_spk))
                if m_ts > max_ts_spk:
                    max_ts_spk = m_ts
        return spk_out, max_ts_spk

    # Include 0.0 solely to measure best_unfolded_acc for the bias diagnostic report,
    # and sweep event-driven bias folding coefficients + common-mode DC offset (prevents 0-floor clipping)
    alphas = [0.0, 0.0045, 0.0055, 0.0064, 0.0075]
    dc_offsets = [0.0, 0.015, 0.020, 0.025]
    s_ratios = [1.0]  # Full 8-bit [-127, +127] dynamic range for Layer 3
    candidate_l3_ths = [2000, 2400, 2800, 3200, 3400, 3600, 3800, 4000, 4400]

    best_calib_acc = -1.0
    best_unfolded_acc = -1.0
    best_params = (0.0055, 0.020, 1.0, 3600)

    for alpha in alphas:
        dc_list = [0.0] if alpha == 0.0 else dc_offsets
        for dc in dc_list:
            w3_folded = w3_f.copy()
            for c in range(10):
                w3_folded[c, :] += (b3_f[c] * alpha) + dc
            max_w3 = np.max(np.abs(w3_folded))

            for s_ratio in s_ratios:
                scale3 = s_ratio * (127.0 / max_w3)
                q_fc = np.clip(np.round(w3_folded * scale3), -127, 127).astype(np.int32)

                for th_l3 in candidate_l3_ths:
                    spk_out_b, max_ts_spk = simulate_sequential_batch(q_fc, padded_events_calib, th_l3, n_calib)
                    tot_per_img = np.sum(spk_out_b, axis=1)
                    preds = np.argmax(spk_out_b, axis=1)
                    correct = int(np.sum((tot_per_img > 0) & (preds == calib_lbls)))
                    total_spk = int(np.sum(tot_per_img))
                    pred_hist = np.bincount(preds, minlength=10)

                    acc = correct / n_calib * 100.0
                    avg_spk = total_spk / n_calib
                    max_class_share = np.max(pred_hist) / n_calib
                    if alpha == 0.0:
                        if 2.0 <= avg_spk <= 30.0 and acc > best_unfolded_acc:
                            best_unfolded_acc = acc
                    else:
                        # Require < 28 spikes/timestep (fits 32-entry FIFO) and balanced predictions (<17% per class)
                        if max_ts_spk < 28 and 3.0 <= avg_spk <= 32.0 and max_class_share < 0.17 and acc > best_calib_acc:
                            best_calib_acc = acc
                            best_params = (alpha, dc, s_ratio, th_l3)

    BIAS_FOLD_COEFF, DC_OFFSET, best_scale3_ratio, best_th_l3 = best_params
    w3_folded = w3_f.copy()
    for c in range(10):
        w3_folded[c, :] += (b3_f[c] * BIAS_FOLD_COEFF) + DC_OFFSET
    final_scale3 = best_scale3_ratio * (127.0 / np.max(np.abs(w3_folded)))
    q_fc_int = np.clip(np.round(w3_folded * final_scale3), -127, 127).astype(np.int8)
    q_fc_unfolded = np.clip(np.round(w3_f * final_scale3), -127, 127).astype(np.int8)
    q_b3 = np.clip(np.round(b3_f * final_scale3), -127, 127).astype(np.int8)

    print(f"  Optimized Calibration Accuracy   : {best_calib_acc:.2f}% (Without Bias Folding: {best_unfolded_acc:.2f}%)")
    print(f"  Optimized Bias Fold Coeff        : {BIAS_FOLD_COEFF:.4f} (Common-Mode DC Shift: +{DC_OFFSET:.4f})")
    print(f"  Optimized Layer 3 Scale Ratio    : {best_scale3_ratio:.2f} (scale3 = {final_scale3:.2f})")
    print(f"  Layer 2 Threshold (HLS 0x18)     : {base_th}")
    print(f"  Layer 3 Threshold (RTL 0x10)     : {best_th_l3}")
    print(f"  q_fc_w Quantized Dynamic Range   : [{q_fc_int.min()}, {q_fc_int.max()}] "
          f"(Non-zero entries: {np.count_nonzero(q_fc_int)} / {q_fc_int.size})")

    # ─────────────────────────────────────────────────────────────────
    # 5. Full 10,000 Image Hardware-Faithful Sequential Validation
    # ─────────────────────────────────────────────────────────────────
